def main():
    lines = ["# Measures dictionary", "",
             f"{len(MEASURES)} DAX measures, grouped in display folders of the `_Measures` table. Generated by "
             "`src/build_measures_dictionary.py` from the model definition (`src/build_tmdl.py`). "
             "The *Test* column points to [TEST_PLAN.md](TEST_PLAN.md).", ""]
    folder = None
    for name, dax, fmt, f in MEASURES:
        if f != folder:
            folder = f
            lines += ["", f"## {f}", "", "| Measure | Meaning | Format | Test |", "|---|---|---|---|"]
        meaning, test = MEANING.get(name, ("", "-"))
        lines.append(f"| **{name}** | {meaning} | `{fmt or 'text'}` | {test} |")
    lines += ["", "## DAX", ""]
    for name, dax, fmt, f in MEASURES:
        lines += [f"**{name}**", "```dax", f"{name} = {dax}", "```"]
    Path("product/MEASURES_DICTIONARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    missing = [n for n, *_ in MEASURES if n not in MEANING]
    print("measures:", len(MEASURES), "missing meaning:", missing)


if __name__ == "__main__":
    main()
